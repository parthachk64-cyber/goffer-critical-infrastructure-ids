"""Command line: demo, benchmark, report. Errors are reported as one actionable line, exit code 2."""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

from infra_ids.pipeline import run_experiment
from infra_ids.report import resolve_run, write_report
from infra_ids.schema import SchemaError
from infra_ids.synthetic import generate_pair


def _demo(args) -> Path:
    with tempfile.TemporaryDirectory() as tmp:
        # Inputs are regenerated from the seed; their hashes are recorded in the manifest.
        paths = generate_pair(args.seed, Path(tmp))
        return run_experiment(
            paths["train"], paths["test"], args.seed, args.out, "synthetic_demonstration",
            max_alerts=None,
            notes=["Synthetic demonstration: generated by infra_ids.synthetic; not real traffic."],
        )  # fmt: skip


def _benchmark(args) -> Path:
    return run_experiment(
        args.train_csv, args.test_csv, args.seed, args.out, "unsw_nb15_official_partitions",
        max_alerts=args.max_alerts,
        notes=["UNSW-NB15 official training/testing CSVs; see docs/data.md for provenance and terms."],
    )  # fmt: skip


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="infra_ids", description="Offline defensive flow-record detector comparison.")
    sub = ap.add_subparsers(dest="command", required=True)
    d = sub.add_parser("demo", help="run on the seeded synthetic fixture")
    d.add_argument("--seed", type=int, default=42)
    d.add_argument("--out", default="runs/demo")
    b = sub.add_parser("benchmark", help="run on the UNSW-NB15 training/testing CSVs")
    b.add_argument("--train-csv", required=True)
    b.add_argument("--test-csv", required=True)
    b.add_argument("--seed", type=int, default=42)
    b.add_argument("--out", default="runs/benchmark")
    b.add_argument("--max-alerts", type=int, default=5000, help="alert queue capacity")
    r = sub.add_parser("report", help="regenerate tables, plots and report.md from a saved run")
    r.add_argument("--run", required=True, help="run directory, or a base directory with a LATEST pointer")
    return ap


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.command == "report":
            run = resolve_run(args.run)
            print(f"report written: {write_report(run)}")
            return 0
        run = _demo(args) if args.command == "demo" else _benchmark(args)
        print(f"run complete: {run}\nreport: {run / 'report.md'}")
        return 0
    except SchemaError as exc:
        print("input error:\n  " + "\n  ".join(exc.problems), file=sys.stderr)
    except FileNotFoundError as exc:
        print(f"error: {exc}", file=sys.stderr)
    return 2
